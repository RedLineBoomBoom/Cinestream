const WEEKLY_DATASETS: GenreCategory[][] = [
  WEEK_1_GENRES, // Week index 0 (Week 1 starting 20 Sep 2026)
  WEEK_2_GENRES, // Week index 1 (Week 2 starting 27 Sep 2026)
];

const MS_PER_DAY = 24 * 60 * 60 * 1000;
const MS_PER_WEEK = 7 * MS_PER_DAY;

/**
 * Computes calendar information for a given week index
 */
export function getWeekScheduleInfo(weekIndex: number): WeekScheduleInfo {
  const start = new Date(ROTATION_ANCHOR_DATE.getTime() + weekIndex * MS_PER_WEEK);
  const end = new Date(start.getTime() + 6 * MS_PER_DAY + 23 * 3600000 + 59 * 60000 + 59000);

  const startDay = start.getDate();
  const startMonthEn = start.toLocaleDateString('en-US', { month: 'short' });
  const startMonthId = start.toLocaleDateString('id-ID', { month: 'short' });

  const endDay = end.getDate();
  const endMonthEn = end.toLocaleDateString('en-US', { month: 'short' });
  const endMonthId = end.toLocaleDateString('id-ID', { month: 'short' });
  const year = end.getFullYear();

  return {
    index: weekIndex,
    weekNumber: weekIndex + 1,
    startDate: start,
    endDate: end,
    labelEn: `Week ${weekIndex + 1}: ${startDay} ${startMonthEn} – ${endDay} ${endMonthEn} ${year}`,
    labelId: `Pekan ${weekIndex + 1}: ${startDay} ${startMonthId} – ${endDay} ${endMonthId} ${year}`,
    badgeEn: `Week of ${startDay} ${startMonthEn} ${year}`,
    badgeId: `Edisi ${startDay} ${startMonthId} ${year}`,
  };
}

/**
 * Calculates current active week index based on real-time clock.
 * For dates prior to 20 September 2026, returns Week 1 (index 0) so
 * the new featured recommendations are immediately active and visible.
 */
export function getActiveWeekIndex(now: Date = new Date()): number {
  const diff = now.getTime() - ROTATION_ANCHOR_DATE.getTime();
  if (diff < 0) {
    // Current date is before 20 Sep 2026: feature Week 1
    return 0;
  }
  return Math.floor(diff / MS_PER_WEEK);
}

/**
 * Returns the genre categories and metadata for the active week.
 * Automatically cycles through available datasets infinitely.
 */
export function getCuratedGenresForWeek(weekIndex: number): {
  weekInfo: WeekScheduleInfo;
  genres: GenreCategory[];
} {
  const weekInfo = getWeekScheduleInfo(weekIndex);
  
  // Normal cyclic index for dataset
  const cycleIndex = Math.abs(weekIndex) % WEEKLY_DATASETS.length;
  const genres = WEEKLY_DATASETS[cycleIndex];

  return {
    weekInfo,
    genres,
  };
}

/**
 * Returns available preset weeks for user preview in UI
 */
export function getAvailablePreviewWeeks(): WeekScheduleInfo[] {
  return [
    getWeekScheduleInfo(0), // Week 1 (20 Sep - 26 Sep 2026)
    getWeekScheduleInfo(1), // Week 2 (27 Sep - 3 Oct 2026)
  ];
}

